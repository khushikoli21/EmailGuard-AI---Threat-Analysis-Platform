import React, { useState, useEffect } from 'react';
import { FileSearch, ShieldAlert, ArrowRight, RefreshCw, Calendar, Shield } from 'lucide-react';
import { fetchReports } from '../../services/api';

interface ReportsViewProps {
  onSelectReportEmailId: (emailId: string) => void;
}

export const ReportsView: React.FC<ReportsViewProps> = ({ onSelectReportEmailId }) => {
  const [reports, setReports] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);

  const loadData = async () => {
    try {
      setLoading(true);
      const data = await fetchReports();
      setReports(data);
    } catch (err) {
      console.error('[REPORTS] Load error:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadData();
  }, []);

  return (
    <div className="flex-1 overflow-y-auto p-4 sm:p-6 bg-slate-50 space-y-6">
      <div className="flex items-center justify-between pb-3 border-b border-slate-200">
        <div>
          <h2 className="text-xl font-bold text-slate-900 tracking-tight">Threat Analysis Reports</h2>
          <p className="text-xs text-slate-500">
            Dossiers generated by the AI multi-agent detection pipeline for your mailbox
          </p>
        </div>
        <button
          onClick={loadData}
          className="p-1.5 bg-white border border-slate-200 rounded-lg text-slate-600 hover:text-slate-900 shadow-2xs"
        >
          <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin' : ''}`} />
        </button>
      </div>

      {loading ? (
        <div className="p-12 text-center text-xs text-slate-400">Loading reports from database...</div>
      ) : reports.length === 0 ? (
        <div className="p-12 bg-white rounded-xl border border-slate-200 text-center text-slate-500 space-y-2">
          <FileSearch className="w-8 h-8 text-slate-400 mx-auto" />
          <h4 className="font-bold text-slate-800 text-sm">No threat reports generated yet</h4>
          <p className="text-xs text-slate-400 max-w-sm mx-auto">
            Open any email from your inbox and click <strong>Analyze Email</strong> to generate an evidence-backed threat dossier.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {reports.map((rep) => (
            <div
              key={rep.id}
              onClick={() => onSelectReportEmailId(rep.emailId)}
              className="bg-white rounded-xl border border-slate-200 p-4 shadow-xs hover:border-blue-400 transition-all cursor-pointer group space-y-3"
            >
              <div className="flex items-start justify-between gap-2">
                <div className="space-y-0.5 min-w-0">
                  <span className="text-[10px] font-mono font-semibold text-slate-400 uppercase tracking-wider block">
                    ID: {rep.id.slice(0, 8)}...
                  </span>
                  <h3 className="font-bold text-slate-900 text-sm group-hover:text-blue-600 transition-colors truncate">
                    {rep.emailSubject}
                  </h3>
                  <div className="text-xs text-slate-500 font-mono truncate">
                    {rep.senderEmail}
                  </div>
                </div>

                <div className="shrink-0 text-right">
                  <span
                    className={`inline-block px-2.5 py-0.5 rounded text-xs font-mono font-bold uppercase border ${
                      rep.classification === 'Phishing'
                        ? 'bg-rose-50 text-rose-800 border-rose-200'
                        : rep.classification === 'Suspicious'
                        ? 'bg-amber-50 text-amber-800 border-amber-200'
                        : 'bg-emerald-50 text-emerald-800 border-emerald-200'
                    }`}
                  >
                    {rep.classification}
                  </span>
                  <div className="text-[11px] font-mono font-semibold text-slate-500 mt-0.5">
                    Risk {rep.riskScore}/100
                  </div>
                </div>
              </div>

              <p className="text-xs text-slate-600 line-clamp-2 leading-relaxed font-sans">
                {rep.explanation}
              </p>

              <div className="pt-2 border-t border-slate-100 flex items-center justify-between text-[11px] text-slate-400">
                <span className="flex items-center gap-1 font-mono">
                  <Calendar className="w-3 h-3 text-slate-400" />
                  {new Date(rep.createdAt).toLocaleDateString()}
                </span>
                <span className="text-blue-600 font-bold group-hover:underline flex items-center gap-1">
                  <span>View Dossier</span>
                  <ArrowRight className="w-3 h-3" />
                </span>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
};
